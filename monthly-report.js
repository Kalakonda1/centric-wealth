/*!
 * Centric Wealth - MonthlyReport
 * Builds a monthly financial report from the app's local data and downloads it as a file.
 * Runs entirely in the browser: no backend, no API calls.
 *
 *   const text = MonthlyReport.build(data, '2026-10', 'md');   // or 'txt'
 *   MonthlyReport.download(data, '2026-10', 'md');             // saves Financial_Report_October_2026.md
 *
 * data = { transactions, accounts, debts, bills, settings } as loaded from IndexedDB.
 */
(function (global) {
  'use strict';

  const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
  const BANK_TYPES = ['Checking', 'Savings', 'Cash'];
  const isBank = (a) => a.kind === 'bank' || (!a.kind && BANK_TYPES.includes(a.type));
  const isCard = (d) => d.kind === 'credit' || d.type === 'Credit Card';
  const acctType = (t) => (t.accountType === 'bank' || t.accountType === 'credit' ? t.accountType : 'other');
  const sum = (arr, f) => arr.reduce((s, x) => s + (Number(f(x)) || 0), 0);

  function fileName(month, format = 'md') {
    const [y, m] = month.split('-').map(Number);
    return `Financial_Report_${MONTHS[m - 1]}_${y}.${format === 'txt' ? 'txt' : 'md'}`;
  }

  /** All the numbers in the report, independent of formatting. */
  function aggregate(data, month, opts = {}) {
    const all = data.transactions || [];
    const txs = all.filter((t) => String(t.date).slice(0, 7) === month);
    const incomeTx = txs.filter((t) => t.type === 'income');
    const expenseTx = txs.filter((t) => t.type === 'expense');
    const income = sum(incomeTx, (t) => Math.abs(t.amount));
    const expenses = sum(expenseTx, (t) => Math.abs(t.amount));

    const byType = { credit: 0, bank: 0, other: 0 };
    const cats = {};
    expenseTx.forEach((t) => {
      const k = acctType(t), a = Math.abs(t.amount);
      byType[k] += a;
      const c = (cats[t.category || 'Other'] ||= { category: t.category || 'Other', total: 0, credit: 0, bank: 0, other: 0, count: 0 });
      c.total += a; c[k] += a; c.count++;
    });
    const categories = Object.values(cats).sort((a, b) => b.total - a.total);

    const banks = (data.accounts || []).filter(isBank).map((a) => ({ name: a.name, type: a.type || 'Bank', balance: Number(a.balance) || 0 }));
    const cards = (data.debts || []).filter(isCard).map((d) => ({ name: d.name, apr: Number(d.apr) || 0, balance: Number(d.balance) || 0 }));
    const bankTotal = sum(banks, (a) => a.balance), cardTotal = sum(cards, (d) => d.balance);

    // Subscriptions: detected from transactions when the scanner is loaded, otherwise from Bills.
    let subscriptions = [];
    if (global.RecurringScanner) {
      const { items } = global.RecurringScanner.analyze(all, { bills: data.bills || [], decisions: (data.settings || {}).recurringDecisions || {} });
      subscriptions = items.filter((i) => i.kind === 'subscription' && i.active && i.status !== 'cancelled')
        .map((i) => ({ name: i.merchant, billing: i.cadence, amount: i.lastAmount, monthly: i.monthlyCost }));
    }
    if (!subscriptions.length) {
      subscriptions = (data.bills || []).filter((b) => b.isSubscription && b.active !== false)
        .map((b) => ({ name: b.name, billing: b.frequency || 'monthly', amount: Number(b.amount) || 0, monthly: b.frequency === 'yearly' ? b.amount / 12 : Number(b.amount) || 0 }));
    }
    subscriptions.sort((a, b) => b.monthly - a.monthly);

    return {
      month, label: (() => { const [y, m] = month.split('-').map(Number); return `${MONTHS[m - 1]} ${y}`; })(),
      generatedAt: opts.generatedAt || new Date(),
      currency: (data.settings && data.settings.currency) || 'USD',
      income, expenses, net: income - expenses, savingsRate: income > 0 ? (income - expenses) / income : null,
      incomeCount: incomeTx.length, expenseCount: expenseTx.length,
      byType, categories,
      banks, cards, bankTotal, cardTotal, netBalance: bankTotal - cardTotal,
      subscriptions, subscriptionsMonthly: sum(subscriptions, (s) => s.monthly),
    };
  }

  /** Builds the report text. format: 'md' (Markdown) or 'txt' (plain text with aligned columns). */
  function build(data, month, format = 'md', opts = {}) {
    const r = aggregate(data, month, opts);
    const nf = new Intl.NumberFormat('en-US', { style: 'currency', currency: r.currency });
    const $ = (n) => nf.format(Number(n) || 0);
    const pct = (a, b) => (b > 0 ? `${Math.round((a / b) * 100)}%` : '-');
    const asOf = toISO(r.generatedAt);
    const cap = (s) => String(s).charAt(0).toUpperCase() + String(s).slice(1);
    return format === 'txt' ? asText(r, $, pct, asOf, cap) : asMarkdown(r, $, pct, asOf, cap);
  }

  function asMarkdown(r, $, pct, asOf, cap) {
    const esc = (s) => String(s).replace(/\|/g, '\\|');
    const L = [];
    L.push(`# Financial Report: ${r.label}`, '', `_Generated by Centric Wealth on ${asOf} from data stored on this device. Balances are as of that date._`, '');

    L.push('## Summary', '', '| | Amount |', '|---|---:|',
      `| Income (${r.incomeCount} deposit${r.incomeCount === 1 ? '' : 's'}) | ${$(r.income)} |`,
      `| Expenses (${r.expenseCount} transaction${r.expenseCount === 1 ? '' : 's'}) | ${$(r.expenses)} |`,
      `| **Net cash flow** | **${$(r.net)}** |`,
      `| Savings rate | ${r.savingsRate == null ? '-' : Math.round(r.savingsRate * 100) + '%'} |`, '');

    L.push('## Balances', '', '| Account | Type | Balance |', '|---|---|---:|');
    r.banks.forEach((a) => L.push(`| ${esc(a.name)} | Bank (${esc(a.type)}) | ${$(a.balance)} |`));
    r.cards.forEach((d) => L.push(`| ${esc(d.name)} | Credit card${d.apr ? `, ${d.apr}% APR` : ''} | -${$(d.balance)} |`));
    if (!r.banks.length && !r.cards.length) L.push('| No bank accounts or cards yet | | |');
    L.push(`| **Total bank balance** | | **${$(r.bankTotal)}** |`, `| **Total credit card debt** | | **-${$(r.cardTotal)}** |`, `| **Combined net balance** | | **${$(r.netBalance)}** |`, '');

    L.push('## Spending by account type', '', '| Paid with | Amount | Share |', '|---|---:|---:|',
      `| Credit cards | ${$(r.byType.credit)} | ${pct(r.byType.credit, r.expenses)} |`,
      `| Bank accounts | ${$(r.byType.bank)} | ${pct(r.byType.bank, r.expenses)} |`);
    if (r.byType.other > 0) L.push(`| Not linked to an account | ${$(r.byType.other)} | ${pct(r.byType.other, r.expenses)} |`);
    L.push('');

    L.push(`## Subscriptions (${r.subscriptions.length} active, ${$(r.subscriptionsMonthly)}/month)`, '');
    if (r.subscriptions.length) {
      L.push('| Subscription | Billing | Charge | Per month |', '|---|---|---:|---:|');
      r.subscriptions.forEach((s) => L.push(`| ${esc(s.name)} | ${cap(s.billing)} | ${$(s.amount)} | ${$(s.monthly)} |`));
      L.push(`| **Total** | | | **${$(r.subscriptionsMonthly)}** |`);
    } else L.push('No active subscriptions found.');
    L.push('');

    L.push('## Spending by category', '');
    if (r.categories.length) {
      L.push('| Category | Total | Credit cards | Bank | Share |', '|---|---:|---:|---:|---:|');
      r.categories.forEach((c) => L.push(`| ${esc(c.category)} | ${$(c.total)} | ${$(c.credit)} | ${$(c.bank)} | ${pct(c.total, r.expenses)} |`));
      L.push(`| **Total** | **${$(r.expenses)}** | **${$(r.byType.credit)}** | **${$(r.byType.bank)}** | 100% |`);
    } else L.push('No spending recorded this month.');
    L.push('');
    return L.join('\n');
  }

  function asText(r, $, pct, asOf, cap) {
    const W = 56;
    const line = (ch = '-') => ch.repeat(W);
    const row = (label, value) => { label = String(label); value = String(value); const dots = Math.max(2, W - label.length - value.length - 2); return `${label} ${'.'.repeat(dots)} ${value}`; };
    const table = (head, rows, widths) => {
      const fmtRow = (cells) => cells.map((c, i) => (i === 0 ? String(c).slice(0, widths[0]).padEnd(widths[0]) : String(c).padStart(widths[i]))).join('  ').trimEnd();
      return [fmtRow(head), widths.map((w) => '-'.repeat(w)).join('  '), ...rows.map(fmtRow)];
    };
    const L = [];
    L.push(line('='), `FINANCIAL REPORT - ${r.label.toUpperCase()}`, `Generated by Centric Wealth on ${asOf}`, 'From data stored on this device. Balances as of that date.', line('='), '');
    L.push('SUMMARY', line(),
      row(`Income (${r.incomeCount} deposits)`, $(r.income)), row(`Expenses (${r.expenseCount} transactions)`, $(r.expenses)),
      row('Net cash flow', $(r.net)), row('Savings rate', r.savingsRate == null ? '-' : Math.round(r.savingsRate * 100) + '%'), '');
    L.push('BALANCES', line());
    r.banks.forEach((a) => L.push(row(`${a.name} (${a.type})`, $(a.balance))));
    r.cards.forEach((d) => L.push(row(`${d.name} (credit card)`, '-' + $(d.balance))));
    L.push(line(), row('Total bank balance', $(r.bankTotal)), row('Total credit card debt', '-' + $(r.cardTotal)), row('Combined net balance', $(r.netBalance)), '');
    L.push('SPENDING BY ACCOUNT TYPE', line(),
      row('Credit cards', `${$(r.byType.credit)}  (${pct(r.byType.credit, r.expenses)})`), row('Bank accounts', `${$(r.byType.bank)}  (${pct(r.byType.bank, r.expenses)})`));
    if (r.byType.other > 0) L.push(row('Not linked to an account', `${$(r.byType.other)}  (${pct(r.byType.other, r.expenses)})`));
    L.push('');
    L.push(`SUBSCRIPTIONS (${r.subscriptions.length} active)`, line());
    if (r.subscriptions.length) {
      L.push(...table(['Subscription', 'Billing', 'Per month'], r.subscriptions.map((s) => [s.name, cap(s.billing), $(s.monthly)]), [26, 12, 14]));
      L.push(row('Total per month', $(r.subscriptionsMonthly)));
    } else L.push('No active subscriptions found.');
    L.push('');
    L.push('SPENDING BY CATEGORY', line());
    if (r.categories.length) {
      L.push(...table(['Category', 'Total', 'Cards', 'Bank', 'Share'], r.categories.map((c) => [c.category, $(c.total), $(c.credit), $(c.bank), pct(c.total, r.expenses)]), [16, 11, 10, 10, 5]));
    } else L.push('No spending recorded this month.');
    L.push('');
    return L.join('\n');
  }

  function toISO(d) { const p = (n) => String(n).padStart(2, '0'); return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`; }

  /**
   * Generates the report and saves it straight to the device: a Blob plus a temporary <a download> link.
   * Works in mobile Chrome/Safari and installed PWAs; no server involved. Returns the file name.
   */
  function download(data, month, format = 'md') {
    const name = fileName(month, format);
    const text = build(data, month, format);
    const blob = new Blob([text], { type: format === 'txt' ? 'text/plain;charset=utf-8' : 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url; a.download = name; a.rel = 'noopener'; a.style.display = 'none';
    document.body.appendChild(a); a.click(); a.remove();
    // Keep the URL alive long enough for slower mobile download managers.
    setTimeout(() => URL.revokeObjectURL(url), 60 * 1000);
    return { name, size: blob.size };
  }

  /** On phones that support it (notably iPhone), offers the system share sheet ("Save to Files"). */
  async function share(data, month, format = 'md') {
    const name = fileName(month, format);
    const file = new File([build(data, month, format)], name, { type: format === 'txt' ? 'text/plain' : 'text/markdown' });
    if (!(navigator.canShare && navigator.canShare({ files: [file] }))) return false;
    try { await navigator.share({ files: [file], title: name }); } catch (e) { if (e && e.name !== 'AbortError') throw e; }
    return true;
  }
  const canShareFiles = () => { try { return !!(navigator.canShare && navigator.canShare({ files: [new File(['x'], 'x.txt', { type: 'text/plain' })] })); } catch (_) { return false; } };

  global.MonthlyReport = { version: '1.0.0', build, aggregate, download, share, canShareFiles, fileName };
})(typeof window !== 'undefined' ? window : globalThis);
